namespace Em.Ui.Wpf.Core
{
   /// <summary>The layout of the application main window.</summary>
   public enum ApplicationLayout
   {
      /// <summary>Every screen that is opened becomes its own tab in the main window.</summary>
      MultiTab,
      /// <summary>The main window shows one screen at a time, with home, Back/Forward, and detach.</summary>
      SinglePage
   }
}